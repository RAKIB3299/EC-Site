-- EC site database schema for Oracle Database 12c or later.
-- Run this script while connected to the Oracle schema that will own the tables.

CREATE TABLE users (
    user_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    name        VARCHAR2(100 CHAR) NOT NULL,
    email       VARCHAR2(255 CHAR) NOT NULL,
    password    VARCHAR2(255 CHAR) NOT NULL,
    phone       VARCHAR2(30 CHAR),
    address     VARCHAR2(500 CHAR),
    role        VARCHAR2(20 CHAR) DEFAULT 'CUSTOMER' NOT NULL,
    created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'ADMIN'))
);

CREATE TABLE categories (
    category_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    category_name  VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT pk_categories PRIMARY KEY (category_id),
    CONSTRAINT uq_categories_name UNIQUE (category_name)
);

CREATE TABLE products (
    product_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    category_id   NUMBER NOT NULL,
    product_name  VARCHAR2(200 CHAR) NOT NULL,
    description   VARCHAR2(2000 CHAR),
    price         NUMBER(12, 2) NOT NULL,
    stock         NUMBER(10) DEFAULT 0 NOT NULL,
    image_path    VARCHAR2(500 CHAR),
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_products PRIMARY KEY (product_id),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id)
        REFERENCES categories (category_id),
    CONSTRAINT ck_products_price CHECK (price >= 0),
    CONSTRAINT ck_products_stock CHECK (stock >= 0 AND stock = TRUNC(stock))
);

CREATE TABLE orders (
    order_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id           NUMBER NOT NULL,
    total_price       NUMBER(12, 2) NOT NULL,
    status            VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    shipping_address  VARCHAR2(500 CHAR) NOT NULL,
    order_date        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_orders PRIMARY KEY (order_id),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id)
        REFERENCES users (user_id),
    CONSTRAINT ck_orders_total CHECK (total_price >= 0),
    CONSTRAINT ck_orders_status CHECK (
        status IN ('PENDING', 'CONFIRMED', 'SHIPPED', 'COMPLETED', 'CANCELLED')
    )
);

CREATE TABLE order_items (
    order_item_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id       NUMBER NOT NULL,
    product_id     NUMBER NOT NULL,
    quantity       NUMBER(10) NOT NULL,
    price          NUMBER(12, 2) NOT NULL,
    CONSTRAINT pk_order_items PRIMARY KEY (order_item_id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id),
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id)
        REFERENCES products (product_id),
    CONSTRAINT uq_order_items_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_order_items_quantity CHECK (
        quantity > 0 AND quantity = TRUNC(quantity)
    ),
    CONSTRAINT ck_order_items_price CHECK (price >= 0)
);

