-- ============================================================
-- EC SITE CUSTOMER NOTIFICATIONS AND ORDER TRACKING
-- Run only after APP_USERS and EC_ORDERS exist.
-- Existing order/user/product rows are not changed by these tables.
-- ============================================================

CREATE TABLE ec_order_tracking (
    order_id             NUMBER NOT NULL,
    carrier              VARCHAR2(100 CHAR),
    tracking_number      VARCHAR2(100 CHAR),
    shipment_status      VARCHAR2(50 CHAR),
    tracking_information VARCHAR2(1000 CHAR),
    updated_at           TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_ec_order_tracking PRIMARY KEY (order_id),
    CONSTRAINT fk_ec_tracking_order FOREIGN KEY (order_id)
        REFERENCES ec_orders (order_id)
);

CREATE TABLE ec_notifications (
    notification_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id           NUMBER NOT NULL,
    order_id          NUMBER,
    notification_type VARCHAR2(50 CHAR) NOT NULL,
    title             VARCHAR2(200 CHAR) NOT NULL,
    message           VARCHAR2(1000 CHAR) NOT NULL,
    target_url        VARCHAR2(500 CHAR),
    is_read           NUMBER(1) DEFAULT 0 NOT NULL,
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    read_at           TIMESTAMP,
    CONSTRAINT pk_ec_notifications PRIMARY KEY (notification_id),
    CONSTRAINT fk_ec_notifications_user FOREIGN KEY (user_id)
        REFERENCES app_users (user_id),
    CONSTRAINT fk_ec_notifications_order FOREIGN KEY (order_id)
        REFERENCES ec_orders (order_id),
    CONSTRAINT ck_ec_notifications_read CHECK (is_read IN (0, 1))
);

CREATE INDEX ix_ec_notifications_user_date
    ON ec_notifications (user_id, created_at DESC);

-- The original check did not support the requested processing/delivery states.
ALTER TABLE ec_orders DROP CONSTRAINT ck_ec_orders_status;
ALTER TABLE ec_orders ADD CONSTRAINT ck_ec_orders_status CHECK (
    status IN ('PENDING','CONFIRMED','PROCESSING','SHIPPED',
               'DELIVERED','COMPLETED','CANCELLED')
);
