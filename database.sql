-- ============================================================================
-- EC SITE ORDER TABLES
-- Independent from the legacy ORDERS, SALES, and SALES_ITEMS tables.
-- Run this section only when EC_ORDERS and EC_ORDER_ITEMS do not already exist.
-- ============================================================================

CREATE TABLE ec_orders (
    order_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    user_id           NUMBER NOT NULL,
    total_price       NUMBER(12, 2) NOT NULL,
    status            VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    shipping_address  VARCHAR2(500 CHAR) NOT NULL,
    order_date        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_ec_orders PRIMARY KEY (order_id),
    CONSTRAINT fk_ec_orders_user FOREIGN KEY (user_id)
        REFERENCES app_users (user_id),
    CONSTRAINT ck_ec_orders_total CHECK (total_price >= 0),
    CONSTRAINT ck_ec_orders_status CHECK (
        status IN ('PENDING', 'CONFIRMED', 'SHIPPED', 'COMPLETED', 'CANCELLED')
    )
);

CREATE TABLE ec_order_items (
    order_item_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_id       NUMBER NOT NULL,
    prod_id        NUMBER NOT NULL,
    quantity       NUMBER(10) NOT NULL,
    unit_price     NUMBER(12, 2) NOT NULL,
    CONSTRAINT pk_ec_order_items PRIMARY KEY (order_item_id),
    CONSTRAINT fk_ec_items_order FOREIGN KEY (order_id)
        REFERENCES ec_orders (order_id),
    CONSTRAINT fk_ec_items_product FOREIGN KEY (prod_id)
        REFERENCES products (prod_id),
    CONSTRAINT uq_ec_items_order_product UNIQUE (order_id, prod_id),
    CONSTRAINT ck_ec_items_quantity CHECK (
        quantity > 0 AND quantity = TRUNC(quantity)
    ),
    CONSTRAINT ck_ec_items_price CHECK (unit_price >= 0)
);

COMMIT;

-- ============================================================================
-- EC site authentication (independent from the existing CUSTOMERS table)
-- Run this section only when APP_USERS does not already exist.
-- ============================================================================

CREATE TABLE app_users (
    user_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    first_name     VARCHAR2(100 CHAR) NOT NULL,
    last_name      VARCHAR2(100 CHAR) NOT NULL,
    email          VARCHAR2(255 CHAR) NOT NULL,
    password_hash  VARCHAR2(100 CHAR) NOT NULL,
    phone          VARCHAR2(30 CHAR),
    address        VARCHAR2(500 CHAR),
    role           VARCHAR2(20 CHAR) DEFAULT 'CUSTOMER' NOT NULL,
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_users PRIMARY KEY (user_id),
    CONSTRAINT uq_app_users_email UNIQUE (email),
    CONSTRAINT ck_app_users_role CHECK (role IN ('CUSTOMER', 'ADMIN'))
);

-- Oracle unique constraints are normally case-sensitive. This additional
-- function-based unique index prevents both User@example.com and
-- user@example.com from being registered as separate accounts.
CREATE UNIQUE INDEX uq_app_users_email_ci
    ON app_users (LOWER(email));

COMMIT;

-- ============================================================================
-- EC SITE PRODUCT ID SEQUENCE
-- Live PRODUCTS.PROD_ID maximum was verified as 3515 before this DDL was added.
-- Run only when EC_PRODUCT_SEQ does not already exist; never drop/recreate it.
-- ============================================================================

CREATE SEQUENCE ec_product_seq
    START WITH 3516
    INCREMENT BY 1
    NOCYCLE
    CACHE 20;

-- ============================================================================
-- EC SITE PRODUCT IMAGES
-- Isolated image URL/path data; the legacy PRODUCTS table is not altered.
-- Run only when EC_PRODUCT_IMAGES does not already exist.
-- ============================================================================

CREATE TABLE ec_product_images (
    image_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    prod_id     NUMBER(6) NOT NULL,
    image_url   VARCHAR2(500 CHAR) NOT NULL,
    is_primary  CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_ec_product_images PRIMARY KEY (image_id),
    CONSTRAINT fk_ec_product_images_product FOREIGN KEY (prod_id)
        REFERENCES products (prod_id),
    CONSTRAINT ck_ec_product_images_primary CHECK (is_primary IN ('Y', 'N'))
);

-- Oracle stores NULL entries outside a normal unique index. This expression
-- therefore permits many non-primary rows but only one primary row per product.
CREATE UNIQUE INDEX uq_ec_product_primary_image
    ON ec_product_images (CASE WHEN is_primary = 'Y' THEN prod_id END);

COMMIT;

-- ============================================================================
-- EC SITE PRODUCT IMAGE GALLERY (upgrade for an existing EC_PRODUCT_IMAGES)
-- Run these statements once after confirming DISPLAY_ORDER does not exist.
-- Existing image rows and URLs are preserved.
-- ============================================================================

ALTER TABLE ec_product_images ADD display_order NUMBER(1);

MERGE INTO ec_product_images target
USING (
    SELECT image_id,
           ROW_NUMBER() OVER (
               PARTITION BY prod_id
               ORDER BY CASE WHEN is_primary = 'Y' THEN 0 ELSE 1 END,
                        created_at, image_id
           ) AS rn
    FROM ec_product_images
) source
ON (target.image_id = source.image_id)
WHEN MATCHED THEN UPDATE SET target.display_order = source.rn;

ALTER TABLE ec_product_images
    MODIFY display_order DEFAULT 1 NOT NULL;

ALTER TABLE ec_product_images ADD CONSTRAINT ck_ec_product_image_order
    CHECK (display_order BETWEEN 1 AND 4);

ALTER TABLE ec_product_images ADD CONSTRAINT uq_ec_product_image_order
    UNIQUE (prod_id, display_order);

COMMIT;

